#include <stdint.h>

// ==================== Địa chỉ Base ====================
#define PERIPH_BASE           0x40000000UL
#define APB2PERIPH_BASE       (PERIPH_BASE + 0x10000UL)
#define AHBPERIPH_BASE        (PERIPH_BASE + 0x20000UL)

// ==================== RCC ====================
#define RCC_BASE              (AHBPERIPH_BASE + 0x1000UL)
#define RCC_APB2ENR           (*(volatile uint32_t *)(RCC_BASE + 0x18))

#define RCC_APB2ENR_IOPAEN    (1 << 2)
#define RCC_APB2ENR_SPI1EN    (1 << 12)

// ==================== GPIOA ====================
#define GPIOA_BASE            (APB2PERIPH_BASE + 0x0800UL)
#define GPIOA_CRL             (*(volatile uint32_t *)(GPIOA_BASE + 0x00))
#define GPIOA_CRH             (*(volatile uint32_t *)(GPIOA_BASE + 0x04))
#define GPIOA_BSRR            (*(volatile uint32_t *)(GPIOA_BASE + 0x10))

// ==================== SPI1 ====================
#define SPI1_BASE             (APB2PERIPH_BASE + 0x3000UL)
#define SPI1_CR1              (*(volatile uint32_t *)(SPI1_BASE + 0x00))
#define SPI1_SR               (*(volatile uint32_t *)(SPI1_BASE + 0x08))
#define SPI1_DR               (*(volatile uint32_t *)(SPI1_BASE + 0x0C))

// SPI_CR1 bits
#define SPI_CR1_MSTR          (1 << 2)
#define SPI_CR1_BR_1          (1 << 4)
#define SPI_CR1_SPE           (1 << 6)
#define SPI_CR1_SSI           (1 << 8)
#define SPI_CR1_SSM           (1 << 9)

// SPI_SR bits
#define SPI_SR_RXNE           (1 << 0)
#define SPI_SR_TXE            (1 << 1)

// ==================== GPIO Control ====================
#define OLED_CS_LOW()         GPIOA_BSRR = (1 << 20)  // PA4 reset
#define OLED_CS_HIGH()        GPIOA_BSRR = (1 << 4)   // PA4 set
#define OLED_DC_LOW()         GPIOA_BSRR = (1 << 19)  // PA3 reset (Command)
#define OLED_DC_HIGH()        GPIOA_BSRR = (1 << 3)   // PA3 set (Data)
#define OLED_RST_LOW()        GPIOA_BSRR = (1 << 18)  // PA2 reset
#define OLED_RST_HIGH()       GPIOA_BSRR = (1 << 2)   // PA2 set

